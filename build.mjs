// Builds the userscript, the MV3 extension and the Worker's generated modules from one core.
// Usage: node build.mjs [--api https://gestaltschaft.com/feeds]   (default: http://localhost:8787)

import * as esbuild from 'esbuild';
import fs from 'node:fs/promises';

const i = process.argv.indexOf('--api');
const api = new URL((i > 0 ? process.argv[i + 1] : process.env.XFS_API) || 'http://localhost:8787');
// The API base can include a path (the app lives under /feeds on gestaltschaft.com).
const API = (api.origin + api.pathname).replace(/\/+$/, '');
const { version } = JSON.parse(await fs.readFile('package.json', 'utf8'));

const common = {
  bundle: true,
  format: 'iife',
  target: 'chrome111',
  charset: 'utf8',
  legalComments: 'none',
  define: { __API__: JSON.stringify(API) },
  write: false,
};
const code = async (entry, opts = {}) =>
  (await esbuild.build({ ...common, entryPoints: [entry], ...opts })).outputFiles[0].text;

const header = `// ==UserScript==
// @name         X Feed Share
// @namespace    x-feed-share
// @version      ${version}
// @description  Share your X home feed (For You / Following) publicly, and browse feeds other people share.
// @match        https://x.com/*
// @match        https://twitter.com/*
// @run-at       document-start
// @grant        GM_xmlhttpRequest
// @grant        GM_getValue
// @grant        GM_setValue
// @grant        unsafeWindow
// @connect      ${api.hostname}
// @sandbox      JavaScript
// @inject-into  page
// @noframes
// @downloadURL  ${API}/x-feed-share.user.js
// @updateURL    ${API}/x-feed-share.user.js
// ==/UserScript==
`;

await fs.mkdir('dist/extension', { recursive: true });

const userscript = header + '\n' + await code('userscript/main.js');
await fs.writeFile('dist/x-feed-share.user.js', userscript);

for (const name of ['main', 'bridge', 'background']) {
  await fs.writeFile(`dist/extension/${name}.js`, await code(`extension/${name}.js`));
}
const manifest = JSON.parse(await fs.readFile('extension/manifest.json', 'utf8'));
manifest.version = version;
manifest.host_permissions = [`${api.origin}/*`];
await fs.writeFile('dist/extension/manifest.json', JSON.stringify(manifest, null, 2) + '\n');

const viewer = await code('worker/viewer/main.js', { minify: true });
const gen = s => `// Generated by build.mjs; do not edit.\nexport default ${JSON.stringify(s)};\n`;
await fs.writeFile('worker/src/viewer.gen.js', gen(viewer));
await fs.writeFile('worker/src/userscript.gen.js', gen(userscript));

console.log(`built for ${API}: dist/x-feed-share.user.js, dist/extension/, worker/src/*.gen.js`);
